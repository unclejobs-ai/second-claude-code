#!/usr/bin/env node

import { build } from "esbuild";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const root = join(scriptDir, "..");
const bundlePath = join(root, "mcp", "pdca-state-server.bundle.mjs");

const result = await build({
  entryPoints: [join(root, "mcp", "pdca-state-server.mjs")],
  outfile: bundlePath,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  legalComments: "eof",
  metafile: true,
  sourcemap: false,
  banner: {
    js: [
      "// Generated by `npm run build:mcp`. Do not edit this file directly.",
      "// Third-party license texts: ../THIRD_PARTY_NOTICES.md",
    ].join("\n"),
  },
});

const normalizedBundle = readFileSync(bundlePath, "utf8")
  .replaceAll("\r\n", "\n")
  .replace(/[ \t]+$/gm, "")
  .trimEnd();
writeFileSync(bundlePath, `${normalizedBundle}\n`, "utf8");

function packageRootFromInput(inputPath) {
  const parts = inputPath.replaceAll("\\", "/").split("/");
  const nodeModulesIndex = parts.lastIndexOf("node_modules");
  if (nodeModulesIndex < 0 || !parts[nodeModulesIndex + 1]) return null;
  const packagePartCount = parts[nodeModulesIndex + 1].startsWith("@") ? 2 : 1;
  return join(root, ...parts.slice(nodeModulesIndex, nodeModulesIndex + 1 + packagePartCount));
}

const packageRoots = [...new Set(
  Object.keys(result.metafile.inputs)
    .map(packageRootFromInput)
    .filter(Boolean)
)];

const packages = packageRoots.map((packageRoot) => {
  const packageJson = JSON.parse(readFileSync(join(packageRoot, "package.json"), "utf8"));
  const licenseFiles = readdirSync(packageRoot)
    .filter((fileName) => /^(license|licence|notice|copying)(?:[._-].*)?$/i.test(fileName))
    .sort();
  if (licenseFiles.length === 0) {
    throw new Error(`Bundled package ${packageJson.name} has no top-level license or notice file`);
  }
  return {
    name: String(packageJson.name),
    version: String(packageJson.version),
    declaredLicense: typeof packageJson.license === "string"
      ? packageJson.license
      : JSON.stringify(packageJson.license ?? "UNKNOWN"),
    licenseFiles: licenseFiles.map((fileName) => ({
      fileName,
      text: readFileSync(join(packageRoot, fileName), "utf8").replaceAll("\r\n", "\n").trim(),
    })),
  };
}).sort((a, b) => a.name.localeCompare(b.name));

const noticeLines = [
  "# Third-party notices",
  "",
  "This file is generated by `npm run build:mcp`. The packages below are included",
  "in `mcp/pdca-state-server.bundle.mjs`; keep this file with distributed copies of",
  "the bundle. SCC's own license is in `LICENSE`.",
  "",
];

for (const pkg of packages) {
  noticeLines.push(`## ${pkg.name}@${pkg.version}`, "", `Declared license: ${pkg.declaredLicense}`, "");
  for (const licenseFile of pkg.licenseFiles) {
    noticeLines.push(`Source file: \`${licenseFile.fileName}\``, "");
    noticeLines.push(...licenseFile.text.split("\n").map((line) => `    ${line}`), "");
  }
}

const notices = noticeLines.join("\n")
  .replace(/[ \t]+$/gm, "")
  .trimEnd();
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), `${notices}\n`, "utf8");
